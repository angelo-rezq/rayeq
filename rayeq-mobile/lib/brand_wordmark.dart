class _WordmarkPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 765, size.height / 450);
    for (final path in _wordmarkPaths) {
      canvas.drawPath(path, Paint()..color = const Color(0xfff4f0e8));
    }
  }

  @override
  bool shouldRepaint(covariant _WordmarkPainter old) => false;
}
