class RayeqBrandMark extends StatelessWidget {
  final double progress;
  final double size;
  const RayeqBrandMark({super.key, this.progress = 1, this.size = 136});
  @override
  Widget build(BuildContext context) => SizedBox(
    width: size,
    height: size,
    child: CustomPaint(painter: _BrandPainter(progress)),
  );
}

class _BrandPainter extends CustomPainter {
  final double progress;
  _BrandPainter(this.progress);
  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 640, size.height / 640);
    final frame = RRect.fromRectAndRadius(
      const Rect.fromLTWH(22, 22, 596, 596),
      const Radius.circular(130),
    );
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        const Rect.fromLTWH(0, 0, 640, 640),
        const Radius.circular(140),
      ),
      Paint()..color = const Color(0xff191919),
    );
    canvas.drawRRect(
      frame,
      Paint()
        ..color = const Color(0xffb77a32)
            .withValues(alpha: progress.clamp(0, 1))
        ..style = PaintingStyle.stroke
        ..strokeWidth = 4,
    );
    canvas.translate(152, 78);
    canvas.scale(.9);
    final strokeProgress = (progress / .8).clamp(0.0, 1.0);
    final fillProgress = ((progress - .6) / .4).clamp(0.0, 1.0);
    for (final entry in [
      (_copperPath, const Color(0xffb77a32)),
      (_ivoryPath, const Color(0xfff4f0e8)),
    ]) {
      final path = entry.$1, color = entry.$2;
      if (fillProgress > 0)
        canvas.drawPath(
          path,
          Paint()..color = color.withValues(alpha: fillProgress),
        );
      if (progress < 1)
        for (final metric in path.computeMetrics()) {
          canvas.drawPath(
            metric.extractPath(0, metric.length * strokeProgress),
            Paint()
              ..color = color
              ..style = PaintingStyle.stroke
              ..strokeWidth = 3
              ..strokeCap = StrokeCap.round
              ..strokeJoin = StrokeJoin.round,
          );
        }
    }
  }

  @override
  bool shouldRepaint(covariant _BrandPainter old) => old.progress != progress;
}
